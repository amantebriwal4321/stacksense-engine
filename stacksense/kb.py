def catalog_markdown() -> str:
    """Human readable dump of the catalog for the repo."""
    lines = [
        "# StackSense catalog",
        "",
        "This file is generated from `stacksense/kb.py`. Do not edit it by hand.",
        "Scores run from 1 (weak or easy, depending on the column) to 5.",
        "`ops` is burden: 1 is easy. `lock` is lock-in: 1 is portable.",
        "",
    ]

    def section(title: str, rows: list[dict], cols: list[tuple[str, str]]) -> None:
        lines.append(f"## {title}")
        lines.append("")
        head = "| name | " + " | ".join(label for _, label in cols) + " | sources |"
        sep = "| --- | " + " | ".join("---" for _ in cols) + " | --- |"
        lines.append(head)
        lines.append(sep)
        for row in rows:
            cells = [str(row.get(key, "")) for key, _ in cols]
            urls = ", ".join(s["url"] for s in row.get("sources", []))
            lines.append("| " + row["name"].replace("|", "/") + " | " + " | ".join(cells) + " | " + urls + " |")
        lines.append("")

    section("Frontend", FRONTEND, [
        ("id", "id"), ("seo", "seo"), ("interactivity", "interact"),
        ("complexity", "complexity"), ("ops_burden", "ops"), ("low_end", "low end"),
    ])
    section("Backend", BACKEND, [
        ("id", "id"), ("performance", "perf"), ("complexity", "complexity"),
        ("ops_burden", "ops"), ("users_ceiling", "user ceiling"),
    ])
    section("Database", DATABASE, [
        ("id", "id"), ("acid", "acid"), ("cost_tier", "cost tier"),
        ("lock_in", "lock"), ("users_ceiling", "user ceiling"),
    ])
    section("Hosting", HOSTING, [
        ("id", "id"), ("kind", "kind"), ("ops_burden", "ops"),
        ("baa", "baa"), ("cost_tier", "cost tier"), ("concurrent_ceiling", "socket ceiling"),
    ])
    lines.append("## Retired products the engine will not recommend")
    lines.append("")
    lines.append("| name | severity | note | source |")
    lines.append("| --- | --- | --- | --- |")
    seen = set()
    for row in RETIRED:
        if row["name"] in seen:
            continue
        seen.add(row["name"])
        lines.append(f"| {row['name']} | {row['severity']} | {row['note']} | {row['source']} |")
    lines.append("")
    lines.append("## Regulatory sources")
    lines.append("")
    for key in ("rbi", "dpdp", "gdpr", "hipaa", "pci", "iso"):
        item = SOURCES[key]
        lines.append(f"- {item['title']}: {item['url']}")
    lines.append("")
    return "\n".join(lines)
